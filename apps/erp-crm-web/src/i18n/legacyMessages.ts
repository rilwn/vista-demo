function deepMerge<T>(base: T, translated: unknown): T {
  if (!translated || typeof translated !== 'object' || Array.isArray(translated)) return base;
  const result: Record<PropertyKey, unknown> = { ...(base as object) };
  for (const key of Reflect.ownKeys(translated)) {
    const value = (translated as Record<PropertyKey, unknown>)[key];
    const original = (base as Record<PropertyKey, unknown>)[key];
    result[key] =
      value && typeof value === 'object' && !Array.isArray(value)
        ? deepMerge(original ?? {}, value)
        : value;
  }
  return result as T;
}

function localized<T extends object>(english: T, bulgarian: unknown): T {
  const merged = deepMerge(english, bulgarian);
  return new Proxy(english, {
    get(target, property, receiver) {
      return getOperationsLocale() === 'bg'
        ? Reflect.get(merged, property, receiver)
        : Reflect.get(target, property, receiver);
    },
  });
}

